# -*- coding: utf-8 -*-
"""彼得林奇六类公司 → 该看什么估值/核心指标的映射（纯逻辑，无网络依赖）。

投资决策的「决策总开关」：不同类型公司，该看什么、赌什么、怎么验证完全不同。
这里把「林奇分类 → 该看的核心指标」固化成映射，供投研日记自动推导。
"""
from __future__ import annotations

# 六类公司的关键词 → 类别名（用于从 lynch_type 字符串里模糊匹配）
_CATEGORY_KEYWORDS = {
    "周期": "周期型",
    "快速成长": "快速成长",
    "快速增长": "快速成长",
    "成长": "快速成长",
    "稳定成长": "稳健成长",
    "稳健成长": "稳健成长",
    "缓慢增长": "缓慢增长",
    "红利": "缓慢增长",   # 红利/收息股同缓慢增长类
    "困境反转": "困境反转",
    "反转": "困境反转",
    "资产富余": "资产隐蔽",
    "资产隐蔽": "资产隐蔽",
    "隐蔽资产": "资产隐蔽",
}

# 每类公司 → 该看的核心指标清单（决策时盯这几个数）
_CATEGORY_METRICS = {
    "周期型": [
        "PB 及近10年分位（周期股看 PB 不看 PE，盈利高点 PE 失真）",
        "商品价格/长协价 & 供需库存",
        "股息率（周期底部高股息是安全边际）",
        "产能利用率 / 资本开支",
    ],
    "快速成长": [
        "营收同比增速 & 持续性（PEG 视角）",
        "毛利率 / 净利率趋势（是否被规模摊薄侵蚀）",
        "第二曲线 / 门店 / 单店或 ARPU 等增长引擎",
        "现金流能否跟上扩张（经营现金流 / 资本开支）",
    ],
    "稳健成长": [
        "PE 及近10年分位（成长白马看 PE）",
        "ROE 稳定性（连续多年 >15%）",
        "营收/利润增速与 PE 是否匹配（PEG≈1 为锚）",
        "股息率（成熟期分红回馈）",
    ],
    "缓慢增长": [
        "股息率（核心，收息逻辑）",
        "PB / 每股净资产（估值锚）",
        "分红比例 & 分红可持续性",
        "资产质量（如银行不良率、公用事业现金流）",
    ],
    "困境反转": [
        "亏损收窄 / 扭亏节奏",
        "现金流（经营现金流是否已转正）",
        "资产剥离 / 重组 / 减债信号",
        "PB（破净是反转标的常见特征）",
    ],
    "资产隐蔽": [
        "PB & 每股 NAV（账面 vs 重估价值）",
        "隐蔽资产（土地/股权/牌照等重估空间）",
        "大股东增持 / 回购 / 重组信号",
        "股息率（等待价值兑现期间的持有收益）",
    ],
}


def classify(lynch_type: str) -> str:
    """从 lynch_type 字符串识别林奇类别，返回标准类别名；识别不出返回原文。

    e.g. "周期型（煤炭）" → "周期型"；"快速成长" → "快速成长"；"稳健成长" → "稳健成长"。
    """
    if not lynch_type:
        return ""
    # 长关键词优先，避免「稳健成长」被「成长」误匹配成「快速成长」
    for kw, cat in sorted(_CATEGORY_KEYWORDS.items(), key=lambda x: -len(x[0])):
        if kw in lynch_type:
            return cat
    return lynch_type


def metrics_for(lynch_type: str) -> list[str]:
    """返回该林奇类别该看的核心指标清单；识别不出返回通用清单。"""
    cat = classify(lynch_type)
    return _CATEGORY_METRICS.get(cat, _CATEGORY_METRICS["稳健成长"])
