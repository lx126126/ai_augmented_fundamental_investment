"""同一法人的跨上市地配对（A+H 双上市）——公司级字段的跨代码回填。

背景
----
A+H 双上市时，两个代码是**同一家公司**：同一法人、同一份合并报表，只是上市地与
交易币种不同。但两套数据接口的字段覆盖面差很多 —— 港股接口缺审计意见、主营构成、
公司简介、借款类科目（→ 有息负债/净现金算不出），而 A 股接口有。

中国海油 600938(A) / 00883(H) 实测（2018–2025 共 8 个重叠年度）：

| 指标 | A 股 | 港股 | 结论 |
|---|---|---|---|
| 营业总收入 | 3982.20 亿 | 3982.20 亿 | 逐元一致 |
| 归母净利 | 1220.82 亿 | 1220.82 亿 | 逐元一致 |
| 净利率 / 资产负债率 | 30.67% / 26.71% | 30.67% / 26.71% | 完全相同 |

所以这些字段「港股拿不到」**不是数据源缺失，是取数路径没接**。

边界（务必遵守，改这个模块前先读完）
------------------------------------
1. **只回填公司级字段**：审计意见、主营构成、公司简介、有息负债/净现金、行业排名。
   价格 / 估值分位 / PE / PB / 股息率 / 每股股息 / 市值 / 成交属于**上市地派生**
   字段，永不从这里取 —— A/H 不同价，币种也可能不同（港股股息是港元，A 股是人民币）。
2. **只填空白，不覆盖已有值**。两套接口对同名指标的定义不同：港股接口的
   `operating_revenue` 剔除了「其他」业务（实测差 2.3% ＝ 88.84 亿），ROE 是摊薄
   而 A 股是加权（实测差 1.06pp）。整列覆盖会让同一页出现「一个指标两个值」。
3. **不做整表替换**。港股三表覆盖 1999 年起，而 `annual_rates.*.cagr10` 四项
   **只有港股算得出**（A 股三表只到 2018 起）。回填是**取并集**，不是换成 A 股。
4. **回填必须可追溯**：`build_template_data` 把来源代码记进 `backfill_src`，
   构建脚本据此加脚注。不能在产物上把回填值伪装成本上市地原生数据。
5. **期间必须对齐**：只在两边的「最新年报期」同年时才回填，否则会把不同年份的
   数字拼到一张表里（静默错数）。
"""
from __future__ import annotations

#: (A 股代码, 港股代码)。同一法人只登记一次，双向自动生效。
LISTING_PAIRS: tuple[tuple[str, str], ...] = (
    ("600938", "00883"),  # 中国海洋石油有限公司（沪港两地上市）
)


def _pair_map() -> dict[str, str]:
    m: dict[str, str] = {}
    for a, h in LISTING_PAIRS:
        m[a], m[h] = h, a
    return m


def sibling_code(code: str) -> str | None:
    """返回同法人另一上市地的代码；未登记配对时返回 None。

    入参接受任意写法（600938 / 600938.SH / 00883 / 00883.HK）。
    归一化复用 adapter._norm_code（延迟导入，避免模块级循环依赖）。
    """
    from .adapter import _norm_code

    return _pair_map().get(_norm_code(code))
