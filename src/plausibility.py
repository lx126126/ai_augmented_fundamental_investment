# -*- coding: utf-8 -*-
"""PDF 金标准 vs 接口值：数值可信度判定（生产端 validator + 消费端 adapter 共用）。

⚠️ 刻意放在 `src/` 顶层而不是 `src/validation/` 下：`src/validation/__init__.py` 会把
   `validator`（连带 pymupdf / cninfo 网络栈）拉进 import 路径，而消费端 `src/data/adapter.py`
   被报告链路和 web 服务引用 —— 为一个常量引入 PDF 依赖不划算。本模块**零依赖**。

为什么需要这一层
----------------
reconcile 的机制是「官方年报 PDF 为准，覆盖接口值」——因为接口在「同一控制下企业合并
追溯重述」等情形下会抓错（神华 2025 就是典型）。但 **PDF 解析自己也会错**，错得最多的是
**单位识别**：千元被读成元、百万元被读成万元，错法是整百/整万倍。

这类错误如果不拦住，覆盖会把**正确的接口值改成错的**。2026-09-18 实测：美的 000333
利润表用「单位：千元」，`_UNIT_MULTIPLIER` 漏登记千元 → 销售费用解析成 0.4289 亿
（真值 428.9149 亿）→ 被判为「接口错误」覆盖 → 报告的利润构成饼图上直接显示
「销售费用 0.4 亿 / 管理费用 0.2 亿」。

判据的两条经验依据
------------------
- **真实的重述差异**：通常 1.2~2 倍；神华总资产 9038 vs 6278 = **1.44 倍**（已核对 PDF
  原文：合并资产负债表「资产总计」627,761 百万元），极端如短期借款也就 **31 倍**。
- **单位识别错误**：整百 / 整万倍（交行曾算出 999999 倍）。
→ 因此门槛取 **100 倍**：远高于重述差异，低于单位错误的整百倍。

⚠️ 用**倍率**而不是百分比，有两个原因：
① 百分比判据不对称：`diff = |api-pdf|/pdf*100` 以 PDF 为分母，同样的 1000 倍解析错误，
   「PDF 偏小」算出 99900%，「PDF 偏大」只算出 100% —— 方向不同，一个拦住一个放行。
② 百分比极易写错门槛：1000 倍对应的百分比是 **99,900**，历史上这里写成 `100_000`，
   恰好比 99,900 大一点点，把唯一要防的那一类**整类漏掉**。
"""
from __future__ import annotations

IMPLAUSIBLE_RATIO = 100  # 两侧相差 100 倍以上 → 判为 PDF 解析/单位识别错误


def is_implausible(api_val: float, pdf_val: float) -> bool:
    """两侧量级相差 `IMPLAUSIBLE_RATIO` 倍以上（**对称**），或一侧为 0 另一侧非 0。"""
    a, p = abs(api_val), abs(pdf_val)
    if a == 0 or p == 0:
        return a != p
    return max(a, p) / min(a, p) >= IMPLAUSIBLE_RATIO


# 消费端（adapter）读的是落盘 json 里的 `diff_pct`，手上没有两侧原值，只能用百分比。
# 由倍率**派生**，避免两个阈值各自漂移（历史上生产端 100_000、消费端 1e6，量级都对不上）。
# 注意：这是不对称判据的**下界**用途 —— 「PDF 偏小」方向能拦住；「PDF 偏大」方向由
# 生产端的对称判据负责（那条记录根本不会写进 json）。
IMPLAUSIBLE_DIFF_PCT = (IMPLAUSIBLE_RATIO - 1) * 100  # 100 倍 ⇒ 9900%
